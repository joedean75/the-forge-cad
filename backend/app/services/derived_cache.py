# Fingerprints
# ---------------------------------------------------------------------------

def _digest(parts) -> str:
    return hashlib.sha256("|".join(str(p) for p in parts).encode()).hexdigest()


def _dumped(models, drop: Tuple[str, ...] = ()) -> str:
    """The whole model, minus named outputs.

    Listing the fields to *include* is how a later schema addition silently
    stops being part of the key, so this inverts it: everything counts unless it
    is provably derived.
    """
    return json.dumps(
        [{k: v for k, v in m.model_dump().items() if k not in drop}
         for m in (models or [])],
        sort_keys=True, default=str)


def tree_hash(tree: dict) -> str:
    return hashlib.sha256(json.dumps(tree, sort_keys=True, default=str).encode()).hexdigest()


def geometry_fingerprint(doc, resolution: int, chain: tuple = ()) -> str:
    """Everything that changes what an evaluation would produce.

    Not just the feature tree: a parameter value, the active configuration and
    the resolution all move the body without touching a single node. Anything
    missing here becomes a stale mesh served under a fresh hash, which is the
    one failure a cache must not have — so this is deliberately generous, and
    excludes only what provably cannot change geometry (the material, the name,
    the spec, the revision counter).

    **A derived document's geometry is not in the document.** In-context design
    lets one document read another's body, and nothing above would move when the
    source moved — so `document_service.source_keys` folds in the evaluation
    identity of everything this one derives from, recursively and guarded
    against a cycle by `chain`. It costs one tree walk to discover the common
    case has no sources at all. It belongs *here* rather than at the one caller
    that noticed: `product_fingerprint` builds on this digest, and a staleness
    reading that hashed geometry differently from the geometry cache would
    disagree about freshness in exactly the cases that matter.
    """
    from app.services import document_service

    return _digest([
        "measurements-v2",  # invalidate mesh-derived engineering readings
        tree_hash(doc.feature_tree),
        resolution,
        doc.active_configuration or "",
        # `value` is the *resolved* number the caller is about to write back, not
        # an input — including it would invalidate the key on the very
        # evaluation that produced it.
        _dumped(doc.parameters, drop=("value",)),
        _dumped(doc.configurations),
        document_service.source_keys(doc, resolution, chain + (doc.id,)),
    ])


def _material(doc) -> str:
    return doc.material_id or ""


def _spec(doc) -> str:
    return json.dumps(doc.spec or {}, sort_keys=True, default=str)


def _released(doc) -> str:
    """The letter a package would be built from, and the tree behind it.

    The letter alone is not enough: `release_revision` can be called twice and
    a package built from B is not a package built from the B that came after an
    amendment. The tree is what the archive actually contains.
    """
    revisions = getattr(doc, "revisions", None) or []
    if not revisions:
        return ""
    latest = revisions[-1]
    return f"{latest.letter}:{tree_hash(latest.feature_tree)}"


def _manufacturing(doc) -> str:
    return json.dumps(getattr(doc, "manufacturing", None) or {}, sort_keys=True,
                      default=str)


class Product:
    """One derived product, and the document state it is a reading of.

    `extra` names the request-time settings that belong in the fingerprint —
    the element budget of a solve, the process of a DFM run, the tool of a
    toolpath. They are arguments rather than document fields, so they cannot be
    read off the document and have to be passed in; a product whose fingerprint
    ignored them would report a milling analysis as current for an additive one.
    """

    def __init__(self, kind: str, document_inputs: Tuple[Callable[[Any], str], ...],
                 extra: Tuple[str, ...], description: str):
        self.kind = kind
        self.document_inputs = document_inputs
        self.extra = extra
        self.description = description


#: Which document state each derived product reads, and which call arguments.
#:
#: This is the invalidation matrix, written once. Every entry starts from the
#: geometry fingerprint — nothing downstream survives the body moving — and adds
#: what else it reads. `analysis` reads the material because stress is a
#: property of the material as much as of the shape; `dfm` does not, because
#: none of the topology measurements it makes (wall thickness, draft, tool
#: access) depends on what the part is made of.
PRODUCTS: Dict[str, Product] = {
    "analysis": Product(
        "analysis", (_material,), ("elements", "load_cases", "solver"),
        "linear-static FEA: stress, displacement, safety factor"),
    "dfm": Product(
        "dfm", (), ("process", "build_axis", "resolution"),
        "manufacturability measurements for one process"),
    "cam": Product(
        "cam", (), ("machine", "tool", "stock"),
        "a toolpath and the G-code written from it"),
    "spec": Product(
        "spec", (_material, _spec), (),
        "the score against the document's requirements"),
    "drawing": Product(
        "drawing", (), ("spec",),
        "the projected drawing sheet"),
    # A package is built from a *revision*, so the released letter and the tree
    # behind it are inputs. It still starts from the geometry fingerprint like
    # everything else, which is deliberate: a document edited after a release
    # has a package that no longer describes what is on screen, and that is
    # exactly the thing somebody needs to be told before they send it.
    #
    # The **preset is not** an input, unlike `dfm`'s process. An additive DFM
    # report genuinely does not answer the milling question — the measurements
    # differ. A `printed` package only *adds files* to a `standard` one; the
    # facts in both are the same facts about the same revision. So a standard
    # package is still a current reading, and "do I have a printed one" is
    # answered by `manifest.preset` in the result rather than by calling a
    # perfectly good package stale.
    "package": Product(
        "package", (_material, _released, _manufacturing), (),
        "the handover zip for a released revision"),
}


def evaluated_resolution(doc) -> int:
    """The resolution the document's body was actually evaluated at.

    Not any resolution a *caller* passes. `dfm` takes a `resolution` argument
    and it means the meshing used for the additive rows, which is a different
    number from the one the body was built with — fingerprinting the geometry on
    the argument made a report stale the instant anyone asked with a different
    one, and current when the body underneath had been rebuilt at another.
    A call-specific resolution belongs in `settings`, where it says what it is.
    """
    return doc.derived.resolution or 128


def analysis_fingerprint(doc, kind: str, settings: Optional[dict] = None) -> str:
    """The fingerprint a derived product of `kind` should be published under.

    Unknown kinds raise rather than defaulting to the geometry fingerprint. A
    product silently fingerprinted on geometry alone looks current after the
    input it actually depends on changes, which is precisely the failure this
    module exists to make impossible.
    """
    product = PRODUCTS.get(kind)
    if product is None:
        raise KeyError(f"no derived product {kind!r}; known: {', '.join(sorted(PRODUCTS))}")
    settings = settings or {}
    parts = [kind, geometry_fingerprint(doc, evaluated_resolution(doc))]
    parts.extend(read(doc) for read in product.document_inputs)
    parts.extend(
        json.dumps(settings.get(name), sort_keys=True, default=str)
        for name in product.extra)
    return _digest(parts)


